CREATE TYPE statut_temoignage AS ENUM ('EN_ATTENTE', 'APPROUVE', 'REFUSE');

ALTER TABLE participant
    ADD COLUMN consentement_donnees TIMESTAMP(3) NULL,
    ADD COLUMN fuseau_horaire VARCHAR(64) NOT NULL DEFAULT 'UTC',
    ADD COLUMN date_creation TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3);

ALTER TABLE temoignage_participant
    DROP CONSTRAINT temoignage_participant_ibfk_1;

ALTER TABLE temoignage
    ADD COLUMN date_moderation TIMESTAMP(3) NULL,
    ADD COLUMN id_moderateur INTEGER NULL,
    ADD COLUMN id_participant INTEGER NULL,
    ADD COLUMN image_privee VARCHAR(255) NULL,
    ADD COLUMN statut statut_temoignage NOT NULL DEFAULT 'EN_ATTENTE',
    ALTER COLUMN id_temoignage ADD GENERATED BY DEFAULT AS IDENTITY,
    ALTER COLUMN date_temoignage TYPE TIMESTAMP(3),
    ALTER COLUMN date_temoignage SET DEFAULT CURRENT_TIMESTAMP(3);

SELECT setval(
    pg_get_serial_sequence('temoignage', 'id_temoignage'),
    COALESCE(MAX(id_temoignage), 1),
    MAX(id_temoignage) IS NOT NULL
)
FROM temoignage;

ALTER TABLE temoignage_participant
    ADD CONSTRAINT temoignage_participant_ibfk_1
    FOREIGN KEY (id_temoignage) REFERENCES temoignage (id_temoignage)
    ON DELETE RESTRICT ON UPDATE CASCADE;

CREATE TABLE engagement (
    id_engagement SERIAL NOT NULL,
    id_participant INTEGER NOT NULL,
    lieu_engagement VARCHAR(120) NOT NULL,
    jours_choisis INTEGER NOT NULL,
    date_creation TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    CONSTRAINT engagement_pkey PRIMARY KEY (id_engagement),
    CONSTRAINT engagement_jours_choisis_chk CHECK (jours_choisis BETWEEN 1 AND 21)
);

CREATE INDEX engagement_participant_date_idx
    ON engagement (id_participant, date_creation);

CREATE TABLE carte (
    id_carte SERIAL NOT NULL,
    id_engagement INTEGER NOT NULL,
    date_creation TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    CONSTRAINT carte_pkey PRIMARY KEY (id_carte)
);

CREATE INDEX carte_engagement_idx ON carte (id_engagement);

CREATE TABLE suivi_journalier (
    id_suivi SERIAL NOT NULL,
    id_participant INTEGER NOT NULL,
    jour INTEGER NOT NULL,
    date_validation TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    CONSTRAINT suivi_journalier_pkey PRIMARY KEY (id_suivi),
    CONSTRAINT suivi_journalier_jour_chk CHECK (jour BETWEEN 1 AND 21)
);

CREATE INDEX suivi_journalier_date_idx ON suivi_journalier (date_validation);
CREATE UNIQUE INDEX suivi_journalier_participant_jour_uq
    ON suivi_journalier (id_participant, jour);

CREATE TABLE session_auth (
    id_session SERIAL NOT NULL,
    empreinte CHAR(64) NOT NULL,
    id_participant INTEGER NULL,
    id_administrateur INTEGER NULL,
    date_creation TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    date_expiration TIMESTAMP(3) NOT NULL,
    CONSTRAINT session_auth_pkey PRIMARY KEY (id_session)
);

CREATE UNIQUE INDEX session_auth_empreinte_uq ON session_auth (empreinte);
CREATE INDEX session_auth_expiration_idx ON session_auth (date_expiration);
CREATE INDEX session_auth_admin_idx ON session_auth (id_administrateur);

CREATE TABLE journal_admin (
    id_action SERIAL NOT NULL,
    id_administrateur INTEGER NULL,
    action VARCHAR(80) NOT NULL,
    cible VARCHAR(80) NOT NULL,
    id_cible VARCHAR(64) NULL,
    details VARCHAR(1000) NULL,
    date_creation TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    CONSTRAINT journal_admin_pkey PRIMARY KEY (id_action)
);

CREATE INDEX journal_admin_date_idx ON journal_admin (date_creation);
CREATE INDEX journal_admin_admin_idx ON journal_admin (id_administrateur);
CREATE INDEX temoignage_statut_date_idx ON temoignage (statut, date_temoignage);
CREATE INDEX temoignage_participant_idx ON temoignage (id_participant);

ALTER TABLE engagement
    ADD CONSTRAINT engagement_ibfk_1
    FOREIGN KEY (id_participant) REFERENCES participant (id_participant)
    ON DELETE CASCADE ON UPDATE CASCADE;

ALTER TABLE carte
    ADD CONSTRAINT carte_ibfk_1
    FOREIGN KEY (id_engagement) REFERENCES engagement (id_engagement)
    ON DELETE CASCADE ON UPDATE CASCADE;

ALTER TABLE suivi_journalier
    ADD CONSTRAINT suivi_journalier_ibfk_1
    FOREIGN KEY (id_participant) REFERENCES participant (id_participant)
    ON DELETE CASCADE ON UPDATE CASCADE;

ALTER TABLE temoignage
    ADD CONSTRAINT temoignage_auteur_ibfk
    FOREIGN KEY (id_participant) REFERENCES participant (id_participant)
    ON DELETE SET NULL ON UPDATE CASCADE,
    ADD CONSTRAINT temoignage_moderateur_ibfk
    FOREIGN KEY (id_moderateur) REFERENCES administrateur (id_administrateur)
    ON DELETE SET NULL ON UPDATE CASCADE;

ALTER TABLE session_auth
    ADD CONSTRAINT session_auth_participant_ibfk
    FOREIGN KEY (id_participant) REFERENCES participant (id_participant)
    ON DELETE CASCADE ON UPDATE CASCADE,
    ADD CONSTRAINT session_auth_admin_ibfk
    FOREIGN KEY (id_administrateur) REFERENCES administrateur (id_administrateur)
    ON DELETE CASCADE ON UPDATE CASCADE;

ALTER TABLE journal_admin
    ADD CONSTRAINT journal_admin_admin_ibfk
    FOREIGN KEY (id_administrateur) REFERENCES administrateur (id_administrateur)
    ON DELETE SET NULL ON UPDATE CASCADE;
